// Run with node tools/police-test.js. Uses the same case, roster and contact rules as the game.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const rows=new Map();
const storage={getItem:key=>rows.get(key),setItem:(key,value)=>rows.set(key,value)};
const context=vm.createContext({window:{sessionStorage:storage},storage});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/department.js'),'utf8'),context);
const department=context.window.PoliceDepartment;
const advance=seconds=>{department.clock+=seconds;department.process();};
assert.equal(department.staff.length,48);
assert.equal(new Set(department.staff.map(s=>s.fingerprintId)).size,48);
assert.deepEqual(Array.from(department.staff.slice(0,16),s=>s.division),[
 ...Array(8).fill('Patrol'),'Metro SWAT','Metro SWAT','Detectives','Detectives','Communications','Forensics','Air Support','Command'
]);
const patrol=Array.from({length:8},()=>department.claim('Patrol','Responding'));
assert.equal(department.claim('Patrol','Responding'),undefined);
department.release(patrol[2]);
assert.equal(department.claim('Patrol','Foot patrol'),patrol[2]);
department.withdraw(patrol[2]);
assert.equal(department.claim('Patrol','Responding'),undefined);
const player={personId:'ah-player'},victim={};
department.identify(player);department.identify(victim);
const at={x:30,y:.15,z:40},door={};
department.touch(player,door,at,'Door handle');
assert.equal(door.contactPrint,player.fingerprintId);
player.gloves=true;
const untouched={};department.touch(player,untouched,at,'Door handle');
assert.equal(untouched.contactPrint,undefined);
const mystery=department.file({kind:'Homicide',at,victim:victim.personId});
const homicide=department.file({kind:'Homicide',at,victim:victim.personId,contact:player.personId,witness:'Patrol',plate:'AH 2819'});
const pending=department.file({kind:'Homicide',at,victim:victim.personId,reported:false});
assert(mystery.evidence.some(e=>e.source==='Door handle'));
for(const member of patrol)department.release(member);
advance(3);
assert.equal(mystery.stage,'Patrol assigned');
assert.notEqual(mystery.patrol,homicide.patrol);
advance(6);
assert.equal(mystery.stage,'Scene review');
advance(2);
assert.equal(mystery.stage,'Lab review');
assert.equal(homicide.stage,'Lab review');
assert.notEqual(mystery.detective,homicide.detective);
advance(10);
assert.equal(mystery.stage,'Open leads','a victim specimen and an incidental fingerprint alone cannot name the offender');
assert.equal(homicide.stage,'Wanted');
assert.equal(pending.stage,'Unreported');
assert(homicide.analyst);
assert.equal(homicide.timeline.length,6);
assert.equal(homicide.timeline[0].from,'Communications');
assert.equal(homicide.timeline.at(-1).from,department.staff.find(s=>s.personId===homicide.detective).name);
department.sightVehicle(player.personId,'AH 2820');
assert.equal(homicide.plate,'AH 2820');
const restored=vm.runInContext('new CityPoliceDepartment(storage)',context);
assert.equal(restored.cases.find(c=>c.id===homicide.id).stage,'Wanted');
assert(restored.unavailable.has(patrol[2].personId));
restored.book(player.personId);
assert.equal(restored.cases.find(c=>c.id===homicide.id).stage,'Booked');
assert.equal(restored.cases.find(c=>c.id===mystery.id).stage,'Open leads');
advance(480);
assert.equal(department.available('Patrol').watch,1);
console.log('Police roster, evidence, casework, bulletins, booking and reload passed.');

